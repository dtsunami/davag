"""Installs `davag_bridge.py` into DaVinci Resolve's `Workspace -> Scripts -> Utility` folder."""

from __future__ import annotations

from pathlib import Path

from davag.config.resolve_paths import discover_resolve

LAUNCHER_TEMPLATE = '''"""davag Bridge — DaVinci Resolve Workspace -> Scripts launcher.

Auto-generated by `davag --install-bridge`. Zero third-party dependencies.
"""

import sys

DAVAG_SRC = {davag_src!r}
if DAVAG_SRC not in sys.path:
    sys.path.insert(0, DAVAG_SRC)

from davag.bridge.server import run_inside_resolve

run_inside_resolve(
    resolve_obj=globals().get("resolve"),
    fusion_obj=globals().get("fusion"),
    bmd_obj=globals().get("bmd"),
    port={port},
)
'''


def install_bridge_script(
    *,
    target_dir: str | Path | None = None,
    port: int = 18765,
) -> Path:
    """Write `davag_bridge.py` into Resolve's Utility scripts directory and return its path."""
    if target_dir is None:
        inst = discover_resolve()
        dest_dir = Path(inst.user_scripts_utility_dir)
    else:
        dest_dir = Path(target_dir)

    # Points straight back to `D:\davag\src` (or wherever davag is installed)
    davag_src = str(Path(__file__).resolve().parents[2])
    dest_dir.mkdir(parents=True, exist_ok=True)
    script_path = dest_dir / "davag_bridge.py"
    content = LAUNCHER_TEMPLATE.format(davag_src=davag_src, port=int(port))
    script_path.write_text(content, encoding="utf-8")
    return script_path